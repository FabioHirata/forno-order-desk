export function translateStatic(root=document.body){const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let text;while(text=walker.nextNode()){const trimmed=text.textContent.trim();if(!text.parentElement?.closest('input,textarea,#order-list,#notice,#form-error'))text.textContent=text.textContent.replace(trimmed,translatedText(trimmed));}for(const element of root.querySelectorAll('[placeholder],[aria-label]'))for(const attr of ['placeholder','aria-label'])if(element.hasAttribute(attr))element.setAttribute(attr,translatedText(element.getAttribute(attr)));document.documentElement.lang=language;document.title=language==='ja'?'Forno — 注文管理':language==='en'?'Forno — orders, calmly':'Forno — pedidos com calma';}

// Language changes are an in-memory UI action; persistence is only best-effort.
export function setLanguage(value, storage) {
  if (!languages.includes(value)) throw new Error('Unsupported language');
  language=value;
  try { (storage ?? localStorage).setItem('forno-language',value); return true; } catch { return false; }
}
export function translatedText(text) {
  const key=messages[text] ? text : Object.keys(messages).find(key=>messages[key].includes(text));
  return key ? t(key) : text;
}
export function orderText(order, field) { return order.demo === true ? t(order[field]) : order[field]; }
